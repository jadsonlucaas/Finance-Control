const MONTHS = Object.freeze({
  jan: 'ene', fev: 'feb', mar: 'mar', abr: 'abr', mai: 'may', jun: 'jun',
  jul: 'jul', ago: 'ago', set: 'sep', out: 'oct', nov: 'nov', dez: 'dic'
});

/** "nov/2026" -> "nov/2026", "fev/2026" -> "feb/2026". */
export function translateMonthLabel(text = '') {
  return String(text).replace(/\b(jan|fev|mar|abr|mai|jun|jul|ago|set|out|nov|dez)\/(\d{4})\b/g, (_, month, year) => `${MONTHS[month]}/${year}`);
}

// Meses em portugues e (ja formatados pelo app) em espanhol.
const MONTH = '((?:jan|fev|mar|abr|mai|jun|jul|ago|set|out|nov|dez|ene|feb|may|sep|oct|dic)\\/\\d{4})';

export const SCREEN_PATTERNS = Object.freeze([
  [new RegExp(`^De ${MONTH}$`), (_, month) => `Desde ${translateMonthLabel(month)}`],
  [new RegExp(`^At[eé] ${MONTH}$`), (_, month) => `Hasta ${translateMonthLabel(month)}`],
  [/^Período: (.+)$/, (_, period) => `Periodo: ${translateMonthLabel(period)}`],
  [/^Gastos Diários \((.+)\)$/, (_, period) => `Gastos diarios (${translateMonthLabel(period)})`],
  [/^Detalhe por Subcategoria - Total (.+)$/, 'Detalle por subcategoría - Total $1'],
  [/^Dia (\d+)$/, 'Día $1'],
  [/^(\d+) dia\(s\) com movimento$/, '$1 día(s) con movimientos'],
  [/^Sem (\d+)$/, 'Sem. $1']
]);

